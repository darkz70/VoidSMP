package me.darkz70.quirks.arcana;

/** Категория слота заклинания — определяет, на каком уровне стихии он открывается. */
public enum ArcanaSpellKind {
    /** Ур. 1 — одно боевое заклинание. */
    COMBAT,
    /** Ур. 2-3 — два защитных заклинания. */
    DEFENSE,
    /** Ур. 4-5 — временные способности. */
    ABILITY,
    /** Ур. 6-8 — воздействие на блоки рядом. */
    BLOCK,
    /** Ур. 20 — мощное заклинание стихии (открывает доступ ко второй стихии). */
    ULTIMATE
}
