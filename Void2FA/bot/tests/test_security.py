import base64
import json
import time
import pytest
from voidsmp_bot.security import decode_secret, signature, headers, verify_response, fresh


def test_secret_formats_and_validation():
    raw = bytes(range(32))
    assert decode_secret(raw.hex()) == raw
    assert decode_secret(base64.b64encode(raw).decode()) == raw
    for value in ["", "short", "00" * 31, "not base64!"]:
        with pytest.raises(ValueError):
            decode_secret(value)


def test_signature_binds_direction_path_time_nonce_and_body():
    secret = bytes(range(32))
    args = ("request", "/v1/poll", 1000, "n" * 32, b'{"cursor":1}')
    sig = signature(secret, *args)
    assert sig == signature(secret, *args)
    for changed in [("response", *args[1:]), ("request", "/v1/command", *args[2:]),
                    ("request", "/v1/poll", 1001, *args[3:]),
                    ("request", "/v1/poll", 1000, "x" * 32, args[4]),
                    ("request", "/v1/poll", 1000, "n" * 32, b'{"cursor":2}')]:
        assert sig != signature(secret, *changed)
    assert not fresh(969, 1000)
    assert fresh(970, 1000)
    assert fresh(1030, 1000)
    assert not fresh(1031, 1000)


def test_response_replay_and_tamper_rejected():
    secret = bytes(range(32)); body = b'{"ok":true}'; nonce = "n" * 32
    ts = int(time.time())
    h = {"X-Void2FA-Timestamp": str(ts), "X-Void2FA-Nonce": nonce,
         "X-Void2FA-Signature": signature(secret, "response", "/v1/poll", ts, nonce, body)}
    verify_response(secret, "/v1/poll", nonce, h, body)
    with pytest.raises(ValueError): verify_response(secret, "/v1/poll", nonce, h, b'{"ok":false}')
    with pytest.raises(ValueError): verify_response(secret, "/v1/poll", "x" * 32, h, body)
    with pytest.raises(ValueError): verify_response(secret, "/v1/command", nonce, h, body)
    h["X-Void2FA-Timestamp"] = str(ts - 100)
    with pytest.raises(ValueError): verify_response(secret, "/v1/poll", nonce, h, body)


